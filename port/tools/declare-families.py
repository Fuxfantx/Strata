"""Declare every remaining shader family in ggml-vulkan-shader-meta.h.

param_block is true only when every source of the family is in the generator's opt-in whitelist, which is what decides
whether the host writes a slot for it.  Longer names come first so a short prefix cannot shadow a longer one.
"""
import re
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SH = ROOT / "third_party/llama.cpp/ggml/src/ggml-vulkan/vulkan-shaders"
META = ROOT / "third_party/llama.cpp/ggml/src/ggml-vulkan/ggml-vulkan-shader-meta.h"

gen = (SH / "vulkan-shaders-gen.cpp").read_text(encoding="utf-8", errors="replace")
names = re.findall(r'string_to_spv\("([A-Za-z0-9_]+)",\s*"([A-Za-z0-9_.]+)"', gen)
fam2src = {}
for n, s in names:
    fam = re.sub(r"_(f16|f32|bf16|q8_0|q4_0|i64|i32|f16acc|fp32)$", "", n)
    fam2src.setdefault(fam, set()).add(s)

m = re.search(r"use_param_block = \{(.*?)\};", gen, re.S)
wl = set(re.findall(r'"([A-Za-z0-9_.]+)"', m.group(1)))

meta = META.read_text(encoding="utf-8", errors="replace")
declared = re.findall(r'\{\s*"([^"]+)"\s*,', meta)


def is_declared(p):
    return any(p.startswith(d) for d in declared if d)


todo = {}
for p, srcs in fam2src.items():
    if is_declared(p):
        continue
    todo[p] = all(s in wl for s in srcs)

rows = sorted(todo, key=lambda p: (-len(p), p))
block = [
    "",
    "    // Remaining families, generated by port/tools/declare-families.py: param_block is true only where every",
    "    // source of the family opts in through PARAM_BLOCK_ENABLED.  Longer names first.",
    "",
]
for p in rows:
    flag = "(1u << 2), true" if todo[p] else "VK_SHADER_MASK_DERIVE, false"
    block.append('    { "%s",%s%s },' % (p, " " * max(1, 30 - len(p)), flag))

# Append at the end of the array so the hand written entries keep priority under first match wins.
end = meta.rindex("};")
meta = meta[:end] + "\n".join(block) + "\n" + meta[end:]
META.write_text(meta, encoding="utf-8", newline="")
print(f"generated {len(rows)} declarations, param_block true for {sum(1 for v in todo.values() if v)}")
